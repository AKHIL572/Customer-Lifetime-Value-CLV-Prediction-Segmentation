from pathlib import Path
import streamlit as st
import pandas as pd

from src.predict import predict_clv

# -----------------------------
# App Configuration
# -----------------------------
st.set_page_config(
    page_title="Customer Lifetime Value Predictor",
    page_icon="📈",
    layout="centered"
)

# -----------------------------
# App Title
# -----------------------------
st.title("📊 Customer Lifetime Value (CLV) Prediction")
st.write(
    "Predict **6-month customer lifetime value** using historical RFM behavior metrics."
)

# -----------------------------
# Sidebar Inputs
# -----------------------------
st.sidebar.header("🧾 Customer Behavior Inputs")

recency = st.sidebar.number_input(
    "Recency (days since last purchase)",
    min_value=0,
    max_value=1000,
    value=30,
    help="Number of days since the customer's last purchase"
)

frequency = st.sidebar.number_input(
    "Frequency (number of purchases)",
    min_value=1,
    max_value=500,
    value=5,
    help="Total number of transactions made by the customer"
)

monetary = st.sidebar.number_input(
    "Total Monetary Value (historical spend)",
    min_value=0.0,
    max_value=1_000_000.0,
    value=500.0,
    help="Total historical spending amount"
)

total_quantity = st.sidebar.number_input(
    "Total Quantity Purchased",
    min_value=1,
    max_value=10_000,
    value=20,
    help="Total quantity of products purchased"
)

# -----------------------------
# Prediction Logic
# -----------------------------
if st.sidebar.button("🔮 Predict CLV"):

    input_data = pd.DataFrame(
        [[recency, frequency, monetary, total_quantity]],
        columns=["Recency", "Frequency", "Monetary", "TotalQuantity"]
    )

    try:
        prediction_df = predict_clv(input_data)
        predicted_clv = prediction_df["Predicted_CLV"].values[0]

    except Exception as e:
        st.error(
            "🚨 Model not found or prediction failed. Please train the model first using:")
        st.code("python src/train.py")
        st.stop()

    # -----------------------------
    # Segmentation
    # -----------------------------
    if predicted_clv < 1000:
        segment = "Low Value Customer"
        color = "🔴"
    elif predicted_clv < 5000:
        segment = "Medium Value Customer"
        color = "🟠"
    else:
        segment = "High Value Customer"
        color = "🟢"

    # -----------------------------
    # Display Results
    # -----------------------------
    st.subheader("📌 Prediction Result")

    st.metric(
        label="Predicted 6-Month CLV",
        value=f"₹ {predicted_clv:,.2f}"
    )

    st.markdown(
        f"### {color} Customer Segment: **{segment}**"
    )

    st.info(
        "CLV represents estimated revenue generated by this customer "
        "over the next 6 months based on historical purchasing behavior."
    )

    with st.expander("ℹ️ Model Architecture"):
        st.write("""
        • Model: Gradient Boosting Regressor  
        • Target Transformation: Log(1 + CLV)  
        • Features: Recency, Frequency, Monetary, TotalQuantity  
        • Hyperparameter tuning: RandomizedSearchCV  
        """)
